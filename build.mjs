import { readFile, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';
const root=new URL('./',import.meta.url);
const read=name=>readFile(new URL(name,root),'utf8');

// All product modules use named, relative imports and named declarations.
// Fail the build on unsupported module syntax instead of shipping a partial bundle.
async function bundle(entry) {
  const blocks=[],seen=new Set();
  async function visit(file) {
    if(seen.has(file)) return;
    seen.add(file);
    let source=await read(file);
    const imports=[...source.matchAll(/^import \{([^}]+)\} from '([^']+)';$/gm)];
    for(const match of imports) {
      const dep=posix.normalize(posix.join(posix.dirname(file),match[2]));
      if(!dep.startsWith('src/')) throw Error('외부 모듈: '+dep);
      await visit(dep);
      source=source.replace(match[0],'const {'+match[1]+'} = modules['+JSON.stringify(dep)+'];');
    }
    const names=[];
    source=source.replace(/^export (async function|function|const|class) ([A-Za-z_$][\w$]*)/gm,(_,kind,name)=>{
      names.push(name);return kind+' '+name;
    });
    if (/^(?:import|export)\s/m.test(source)) throw Error('지원하지 않는 모듈 구문: '+file);
    blocks.push('modules['+JSON.stringify(file)+'] = (function(){\n'+source+'\nreturn {'+names.join(',')+'};\n})();');
  }
  await visit(entry);
  return '(function(){\n"use strict";\nconst modules=Object.create(null);\n'+blocks.join('\n')+'\nreturn modules['+JSON.stringify(entry)+'];\n})()';
}
const [page,css,client,server]=await Promise.all([read('index.html'),read('src/style.css'),bundle('src/app.mjs'),bundle('src/ledger.mjs')]);
const output=page.replace('<link rel="stylesheet" href="./src/style.css">',()=>'<style>\n'+css+'\n</style>')
  .replace('<script type="module" src="./src/app.mjs"></script>',()=>'<script>document.addEventListener("DOMContentLoaded",function(){\n'+client.replace(/<\/script/gi,'<\\/script')+';\n});</script>');
await writeFile(new URL('apps-script/Engine.gs',root),'// Generated by build.mjs from the same ES modules used locally.\nvar PilotCore = '+server+';\n');
await writeFile(new URL('apps-script/Index.html',root),output);
console.log('apps-script/Index.html + Engine.gs');
